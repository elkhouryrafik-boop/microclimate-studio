import { useStore } from '../store';
import { getAnalysis } from '../catalog/analyses';
import KpiStrip from './KpiStrip';
import Histogram from './Histogram';
import { formatDateTime } from '../format';

export default function ResultsPanel() {
  const selectedAnalysis = useStore((s) => s.selectedAnalysis);
  const resultsByAnalysis = useStore((s) => s.resultsByAnalysis);
  const runState = useStore((s) => s.runState);
  const runError = useStore((s) => s.runError);

  const def = getAnalysis(selectedAnalysis);
  const results = resultsByAnalysis[selectedAnalysis];

  return (
    <div className="flex flex-col gap-4 p-4 rail-scroll overflow-y-auto" style={{ height: '100%' }}>
      <div>
        <p className="text-xs font-500 mb-1" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)' }}>RESULTS</p>
        <p className="text-sm font-600" style={{ fontFamily: 'var(--font-display)', color: 'var(--ink)' }}>{def.short}</p>
      </div>

      {runState === 'running' && (
        <div className="space-y-3">
          {[0,1,2].map(i => (
            <div key={i}>
              <div className="skeleton h-4 rounded mb-1" style={{ width: `${60 + i * 10}%` }} />
              <div className="skeleton h-8 rounded" style={{ width: `${40 - i * 10}%` }} />
            </div>
          ))}
          <div className="skeleton h-24 rounded" />
          <p className="text-xs" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)' }}>Running simulation...</p>
        </div>
      )}

      {runState === 'error' && (
        <div className="p-3 rounded-lg" style={{ background: 'rgba(179,38,30,0.05)', border: '1px solid rgba(179,38,30,0.2)' }}>
          <p className="text-sm font-500" style={{ fontFamily: 'var(--font-display)', color: 'var(--destructive)' }}>Analysis failed</p>
          <p className="text-xs mt-1" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)' }}>{runError}</p>
        </div>
      )}

      {runState === 'idle' && !results && (
        <p className="text-xs" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)' }}>
          Run an analysis to see results
        </p>
      )}

      {results && runState !== 'running' && (
        <>
          {results.engine === 'fake' && (
            <span
              className="inline-block self-start text-[11px] px-2 py-0.5 rounded"
              title="Generated by the fake engine: plausible-looking, deterministic, not physics."
              style={{ fontFamily: 'var(--font-mono)', background: 'var(--slate-100)', color: 'var(--teal-800)', border: '1px solid var(--slate-200)' }}
            >
              SYNTHETIC — FAKE ENGINE
            </span>
          )}
          <KpiStrip kpis={results.kpis} />
          <div className="pt-3" style={{ borderTop: '1px solid var(--slate-200)' }}>
            <p className="text-xs font-500 mb-2" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)' }}>DISTRIBUTION</p>
            <div className="relative">
              <Histogram bins={results.histogram} valueRange={results.valueRange} />
            </div>
          </div>
          <div className="pt-3 text-xs space-y-1.5" style={{ fontFamily: 'var(--font-mono)', color: 'var(--ink-muted)', borderTop: '1px solid var(--slate-200)' }}>
            <p className="font-500 mb-1" style={{ color: 'var(--ink)' }}>METADATA</p>
            <div className="flex justify-between"><span>Station</span><span style={{ color: 'var(--ink)' }}>{results.metadata.station}</span></div>
            <div className="flex justify-between"><span>Analysis</span><span style={{ color: 'var(--ink)' }}>{results.metadata.analysis_label}</span></div>
            <div className="flex justify-between"><span>Weather</span><span style={{ color: 'var(--ink)' }}>{results.metadata.weather_file}</span></div>
            <div className="flex justify-between"><span>Model</span><span style={{ color: 'var(--ink)' }}>{results.metadata.model}</span></div>
            <div className="flex justify-between"><span>Run time</span><span style={{ color: 'var(--ink)' }}>{results.metadata.duration_s.toFixed(1)}s</span></div>
            <div className="flex justify-between"><span>Timestamp</span><span style={{ color: 'var(--ink)' }}>{formatDateTime(results.metadata.timestamp)}</span></div>
          </div>
        </>
      )}
    </div>
  );
}
